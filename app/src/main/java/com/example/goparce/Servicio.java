package com.example.goparce;

public class Servicio {

    public String titulo;

    public String descripcion;

    public String costo;

    public String cupos;

    public Servicio(

            String titulo,

            String descripcion,

            String costo,

            String cupos
    ) {

        this.titulo = titulo;

        this.descripcion = descripcion;

        this.costo = costo;

        this.cupos = cupos;
    }
}