package com.example.goparce;

public class Noticia {

    public String titulo;

    public String descripcion;

    public String tipo;

    public String link;

    public Noticia(

            String titulo,

            String descripcion,

            String tipo,

            String link
    ) {

        this.titulo = titulo;

        this.descripcion = descripcion;

        this.tipo = tipo;

        this.link = link;
    }
}